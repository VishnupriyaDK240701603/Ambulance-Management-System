"""Simulation event definitions and observer interfaces."""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any


class EventType(str, Enum):
    SIM_STARTED = "SIM_STARTED"
    SIM_PAUSED = "SIM_PAUSED"
    SIM_RESUMED = "SIM_RESUMED"
    SIM_RESET = "SIM_RESET"
    
    AMBULANCE_DEPLOYED = "AMBULANCE_DEPLOYED"
    AMBULANCE_REMOVED = "AMBULANCE_REMOVED"
    AMBULANCE_STATUS_CHANGED = "AMBULANCE_STATUS_CHANGED"
    AMBULANCE_ROUTE_UPDATED = "AMBULANCE_ROUTE_UPDATED"
    AMBULANCE_CONTROL_MODE_CHANGED = "AMBULANCE_CONTROL_MODE_CHANGED"

    EMERGENCY_CREATED = "EMERGENCY_CREATED"
    EMERGENCY_STATUS_CHANGED = "EMERGENCY_STATUS_CHANGED"
    EMERGENCY_ASSIGNED = "EMERGENCY_ASSIGNED"
    EMERGENCY_COMPLETED = "EMERGENCY_COMPLETED"

    HOSPITAL_BEDS_UPDATED = "HOSPITAL_BEDS_UPDATED"
    HOSPITAL_PATIENT_ADMITTED = "HOSPITAL_PATIENT_ADMITTED"
    HOSPITAL_ALERT_SENT = "HOSPITAL_ALERT_SENT"
    AMBULANCE_REALLOCATED = "AMBULANCE_REALLOCATED"

    ROAD_INCIDENT_PLACED = "ROAD_INCIDENT_PLACED"
    ROAD_INCIDENT_CLEARED = "ROAD_INCIDENT_CLEARED"

    POLICE_DISPATCHED = "POLICE_DISPATCHED"
    POLICE_STATUS_CHANGED = "POLICE_STATUS_CHANGED"

    DECISION_RECORDED = "DECISION_RECORDED"
    NOTIFICATION_EMITTED = "NOTIFICATION_EMITTED"

@dataclass
class SimulationEvent:
    event_type: EventType
    timestamp: float
    entity_id: str | None = None
    payload: dict[str, Any] = field(default_factory=dict)
